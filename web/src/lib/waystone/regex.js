/* 경로석 구간 조건 → 게임 창고 검색창에 넣을 정규식.

   표는 '16등급 효율50+ & 몬희30+ 가 37카오스' 까지 알려 주지만, 그런 경로석을 내 창고에서
   찾는 일은 손으로 남는다. 조건을 검색 문자열로 바꿔 복사해 주면 그 간극이 없어진다.

   그리는 일과 나눠 둔 까닭은 DOM 없이 불러 검증할 수 있어야 해서다 —
   web/scripts/check-regex.mjs. */

/** 임계값 → '이 값 이상' 을 뜻하는 정규식 조각.

    정규식에는 수 비교가 없다. 그래서 자릿수로 펼친다 — 50 이상은 '십의 자리가 5~9 인 두
    자리' 이거나 '세 자리' 다.

        band(50)  →  ([5-9].|[1-9]..)%
        band(75)  →  (7[5-9]|[8-9].|[1-9]..)%
        band(120) →  (1[2-9].|[2-9]..)%

    10 미만은 빈 문자열이다 — 한 자리는 이 방식으로 안 갈린다. 수집기가 물어보는 경로석
    속성은 전부 두 자리 이상이라 걸릴 일이 없다. */
export function band(v) {
  const t = Number(v);
  if (isNaN(t) || t < 10) return "";
  if (t >= 1000) return "1...%";
  if (t >= 100) {
    const n = Math.floor(t / 100), r = Math.floor((t % 100) / 10), o = t % 10;
    if (r === 0 && o === 0) return n === 1 ? "(1..|[2-9]..)%" : n === 9 ? "(9..)%" : `([${n}-9]..)%`;
    if (r === 0) return n === 1 ? `(10[${o}-9]|1[1-9].|[2-9]..)%`
      : n === 9 ? `(90[${o}-9]|9[1-9].)%`
        : `(${n}0[${o}-9]|${n}[1-9].|[${n + 1}-9]..)%`;
    if (o === 0) return n === 1 ? `(1[${r}-9].|[2-9]..)%`
      : n === 9 ? `(9[${r}-9].)%`
        : `(${n}[${r}-9].|[${n + 1}-9]..)%`;
    if (n === 1) return r === 9 ? `(19[${o}-9]|[2-9]..)%` : `(1${r}[${o}-9]|1[${r + 1}-9].|[2-9]..)%`;
    if (n === 9) return r === 9 ? `(99[${o}-9])%` : `(9${r}[${o}-9]|9[${r + 1}-9].)%`;
    if (r === 9) return `(${n}9[${o}-9]|[${n + 1}-9]..)%`;
    return `(${n}${r}[${o}-9]|${n}[${r + 1}-9].|[${n + 1}-9]..)%`;
  }
  const a = Math.floor(t / 10), i = t % 10;
  if (i === 0) return a === 9 ? "(9.|[1-9]..)%" : `([${a}-9].|[1-9]..)%`;
  if (i === 9) return a === 9 ? "(99|[1-9]..)%" : a === 8 ? "(89|9.|[1-9]..)%"
    : `(${a}9|[${a + 1}-9].|[1-9]..)%`;
  if (a === 9) return `(9[${i}-9]|[1-9]..)%`;
  if (a === 8) return `(8[${i}-9]|9.|[1-9]..)%`;
  return `(${a}[${i}-9]|[${a + 1}-9].|[1-9]..)%`;
}

/* 축 id → 경로석에 찍힌 줄의 앞자리. 검색창 한도가 250자라 알아볼 수 있는 최소 길이로 끊는다.

     eff    율:.*      ← 몬스터 효율: +54%
     rare   터.*도:.*  ← 몬스터 희귀도: +37%
     iir    템.*도:.*  ← 아이템 희귀도: +28%
     pack   규모:.*    ← 무리 규모: +25%
     bonus  률:.*      ← 경로석 출현 확률: +75%

   '율:' 과 '률:' 이 갈리는 것이 요점이다 — 효율과 확률이 서로 안 걸린다. 마찬가지로
   '터.*도:' 와 '템.*도:' 가 몬스터 희귀도와 아이템 희귀도를 가른다.

   시즌이 바뀌어 게임 글월이 달라지면 여기가 먼저 깨진다. 값이 아니라 글자에 묶여 있다. */
const PREFIX = {
  eff: "율:.*",
  rare: "터.*도:.*",
  iir: "템.*도:.*",
  pack: "규모:.*",
  bonus: "률:.*",
};

/** 축 하나짜리 항. 못 만들면 빈 문자열이다. */
export function term(axis, v) {
  const pre = PREFIX[axis], b = band(v);
  return pre && b ? `"${pre}${b}"` : "";
}

/** 표의 칸 하나 → 검색창에 넣을 문자열.

    parts 는 ((축, 구간), ...) 다 — 비면 등급만, 하나면 단독 구간, 둘이면 조합이다
    (수집기의 waystone_prices.query 와 같은 모양). 검색창에서 공백은 AND 라, 항을 그냥
    이어 붙이면 전부 만족하는 경로석만 남는다.

        forQuery(16, [["eff", 50], ["rare", 30]])
          →  "16등급" "율:.*([5-9].|[1-9]..)%" "터.*도:.*([3-9].|[1-9]..)%"

    등급을 앞에 박는 것은 표의 칸이 등급마다 따로 있기 때문이다. 아이템 종류 줄이
    '경로석 (16등급)' 이라 '16등급' 이면 갈린다. */
export function forQuery(tier, parts = []) {
  return [`"${tier}등급"`, ...parts.map(([a, v]) => term(a, v))].filter(Boolean).join(" ");
}

/** 검색창이 받는 길이. */
export const MAX = 250;
